    ! Append the UTF-8 encoding of cp to out(n+1:), advancing n.
    subroutine put_utf8(out, n, cp)
        character(*), intent(inout) :: out
        integer, intent(inout) :: n
        integer, intent(in) :: cp
        if (cp < 128) then
            if (n + 1 <= len(out)) out(n+1:n+1) = achar(cp)
            n = n + 1
        else if (cp < 2048) then
            if (n + 2 <= len(out)) then
                out(n+1:n+1) = achar(192 + cp / 64)
                out(n+2:n+2) = achar(128 + modulo(cp, 64))
            end if
            n = n + 2
        else if (cp < 65536) then
            if (n + 3 <= len(out)) then
                out(n+1:n+1) = achar(224 + cp / 4096)
                out(n+2:n+2) = achar(128 + modulo(cp / 64, 64))
                out(n+3:n+3) = achar(128 + modulo(cp, 64))
            end if
            n = n + 3
        else
            if (n + 4 <= len(out)) then
                out(n+1:n+1) = achar(240 + cp / 262144)
                out(n+2:n+2) = achar(128 + modulo(cp / 4096, 64))
                out(n+3:n+3) = achar(128 + modulo(cp / 64, 64))
                out(n+4:n+4) = achar(128 + modulo(cp, 64))
            end if
            n = n + 4
        end if
    end subroutine

    ! Decode one code point of s(i:n).  status 0: valid character of adv bytes;
    ! 1: maximal invalid subpart of adv bytes (one U+FFFD); 2: valid but
    ! truncated prefix at the end of the buffer (adv bytes).
    subroutine utf8_step(s, i, n, cp, adv, status)
        character(*), intent(in) :: s
        integer, intent(in) :: i, n
        integer, intent(out) :: cp, adv, status
        integer :: b0, bk, need, lo, hi, k
        b0 = iachar(s(i:i))
        cp = 65533
        status = 0
        adv = 1
        if (b0 < 128) then
            cp = b0
            return
        end if
        if (b0 < 194 .or. b0 > 244) then
            status = 1
            return
        end if
        need = 1
        cp = b0 - 192
        if (b0 >= 224) then
            need = 2
            cp = b0 - 224
        end if
        if (b0 >= 240) then
            need = 3
            cp = b0 - 240
        end if
        lo = 128
        hi = 191
        if (b0 == 224) lo = 160
        if (b0 == 237) hi = 159
        if (b0 == 240) lo = 144
        if (b0 == 244) hi = 143
        do k = 1, need
            if (i + k > n) then
                status = 2
                adv = k
                return
            end if
            bk = iachar(s(i+k:i+k))
            if (bk < lo .or. bk > hi) then
                status = 1
                adv = k
                cp = 65533
                return
            end if
            lo = 128
            hi = 191
            cp = cp * 64 + (bk - 128)
        end do
        adv = need + 1
    end subroutine

    subroutine utf8_to_cps(s, c, n)
        character(*), intent(in) :: s
        integer(int32), allocatable, intent(out) :: c(:)
        integer, intent(out) :: n
        integer :: i, cp, adv, status
        allocate(c(max(1, len(s))))
        n = 0
        i = 1
        do while (i <= len(s))
            call utf8_step(s, i, len(s), cp, adv, status)
            if (status /= 0) cp = 65533
            n = n + 1
            c(n) = cp
            i = i + adv
        end do
    end subroutine

    function cps_to_utf8(c, n) result(s)
        integer(int32), intent(in) :: c(*)
        integer, intent(in) :: n
        character(:), allocatable :: s
        character(:), allocatable :: t
        integer :: i, k
        allocate(character(max(1, 4 * n)) :: t)
        k = 0
        do i = 1, n
            call put_utf8(t, k, int(c(i)))
        end do
        s = t(1:k)
    end function

    ! Replace invalid UTF-8 by U+FFFD (what the tokenizer sees).
    function sanitize_utf8(s) result(r)
        character(*), intent(in) :: s
        character(:), allocatable :: r
        integer(int32), allocatable :: c(:)
        integer :: n
        call utf8_to_cps(s, c, n)
        r = cps_to_utf8(c, n)
    end function

    ! ------------------------------------------------------------------
    ! Unicode classification
    ! ------------------------------------------------------------------

    logical function in_ranges(cp, lo, hi)
        integer, intent(in) :: cp
        integer(int32), intent(in) :: lo(:), hi(:)
        integer :: a, b, m
        in_ranges = .false.
        a = 1
        b = size(lo)
        do while (a < b)
            m = (a + b + 1) / 2
            if (lo(m) <= cp) then
                a = m
            else
                b = m - 1
            end if
        end do
        if (lo(a) <= cp .and. cp <= hi(a)) in_ranges = .true.
    end function

    logical function is_letter(cp)
        integer, intent(in) :: cp
        if (cp < 128) then
            is_letter = (cp >= 97 .and. cp <= 122) .or. (cp >= 65 .and. cp <= 90)
        else
            is_letter = in_ranges(cp, letter_lo, letter_hi)
        end if
    end function

    logical function is_number(cp)
        integer, intent(in) :: cp
        if (cp < 128) then
            is_number = cp >= 48 .and. cp <= 57
        else
            is_number = in_ranges(cp, number_lo, number_hi)
        end if
    end function

    logical function is_space(cp)
        integer, intent(in) :: cp
        if (cp < 128) then
            is_space = cp == 32 .or. (cp >= 9 .and. cp <= 13)
        else if (cp > 12288) then
            is_space = .false.
        else
            is_space = in_ranges(cp, space_lo, space_hi)
        end if
    end function

    logical function is_symbol(cp)   ! [^\s\p{L}\p{N}]
        integer, intent(in) :: cp
        is_symbol = .not. (is_space(cp) .or. is_letter(cp) .or. is_number(cp))
    end function

    ! End (exclusive) of the pre-token starting at c(i), emulating the regex alternation.
    integer function piece_end(c, n, i) result(e)
        integer(int32), intent(in) :: c(*)
        integer, intent(in) :: n, i
        integer :: cp, c1, c2, j, k, r
        cp = c(i)
        ! 1. contractions (?i:'s|'t|'re|'ve|'m|'ll|'d)
        if (cp == 39 .and. i < n) then
            c1 = c(i+1)
            if (c1 >= 65 .and. c1 <= 90) c1 = c1 + 32
            if (c1 == 115 .or. c1 == 116 .or. c1 == 109 .or. c1 == 100) then
                e = i + 2
                return
            end if
            if (i + 1 < n) then
                c2 = c(i+2)
                if (c2 >= 65 .and. c2 <= 90) c2 = c2 + 32
                if ((c1 == 114 .and. c2 == 101) .or. (c1 == 118 .and. c2 == 101) .or. &
                        (c1 == 108 .and. c2 == 108)) then
                    e = i + 3
                    return
                end if
            end if
        end if
        ! 2. [^\r\n\p{L}\p{N}]?\p{L}+
        if (is_letter(cp)) then
            j = i + 1
        else if (cp /= 13 .and. cp /= 10 .and. .not. is_number(cp) .and. i < n) then
            if (is_letter(c(i+1))) then
                j = i + 2
            else
                j = 0
            end if
        else
            j = 0
        end if
        if (j > 0) then
            do while (j <= n)
                if (.not. is_letter(c(j))) exit
                j = j + 1
            end do
            e = j
            return
        end if
        ! 3. \p{N}
        if (is_number(cp)) then
            e = i + 1
            return
        end if
        ! 4.  ?[^\s\p{L}\p{N}]+[\r\n]*
        j = i
        if (cp == 32 .and. i < n) then
            if (is_symbol(c(i+1))) j = i + 1
        end if
        if (is_symbol(c(j))) then
            do while (j <= n)
                if (.not. is_symbol(c(j))) exit
                j = j + 1
            end do
            do while (j <= n)
                if (c(j) /= 10 .and. c(j) /= 13) exit
                j = j + 1
            end do
            e = j
            return
        end if
        ! 5-7. whitespace: cp is a space here
        r = i
        do while (r <= n)
            if (.not. is_space(c(r))) exit
            r = r + 1
        end do
        k = 0
        do j = r - 1, i, -1
            if (c(j) == 10 .or. c(j) == 13) then
                k = j
                exit
            end if
        end do
        if (k > 0) then
            e = k + 1                 ! \s*[\r\n]+
        else if (r > n) then
            e = r                     ! \s+(?!\S) at end of text
        else if (r - 1 > i) then
            e = r - 1                 ! \s+(?!\S): leave the last space for the next piece
        else
            e = i + 1                 ! \s+
        end if
    end function

    ! ------------------------------------------------------------------
    ! NFC
    ! ------------------------------------------------------------------

    integer function ccc_of(cp)
        integer, intent(in) :: cp
        integer :: a, b, m
        ccc_of = 0
        if (cp < 768) return
        a = 1
        b = size(ccc_lo)
        do while (a < b)
            m = (a + b + 1) / 2
            if (ccc_lo(m) <= cp) then
                a = m
            else
                b = m - 1
            end if
        end do
        if (ccc_lo(a) <= cp .and. cp <= ccc_hi(a)) ccc_of = ccc_val(a)
    end function

    integer function find_decomp(cp) result(k)
        integer, intent(in) :: cp
        integer :: a, b, m
        k = 0
        a = 1
        b = size(dec_cp)
        do while (a <= b)
            m = (a + b) / 2
            if (dec_cp(m) == cp) then
                k = m
                return
            else if (dec_cp(m) < cp) then
                a = m + 1
            else
                b = m - 1
            end if
        end do
    end function

    integer function compose_pair(a, b) result(c)
        integer, intent(in) :: a, b
        integer :: lo, hi, m
        integer(int64) :: key, kk
        c = 0
        if (a >= 4352 .and. a < 4371 .and. b >= 4449 .and. b < 4470) then   ! Hangul L+V
            c = 44032 + ((a - 4352) * 21 + (b - 4449)) * 28
            return
        end if
        if (a >= 44032 .and. a <= 55203 .and. b > 4519 .and. b < 4547) then ! Hangul LV+T
            if (modulo(a - 44032, 28) == 0) c = a + (b - 4519)
            return
        end if
        key = int(a, int64) * 2097152_int64 + b
        lo = 1
        hi = size(comp_a)
        do while (lo <= hi)
            m = (lo + hi) / 2
            kk = int(comp_a(m), int64) * 2097152_int64 + comp_b(m)
            if (kk == key) then
                c = comp_c(m)
                return
            else if (kk < key) then
                lo = m + 1
            else
                hi = m - 1
            end if
        end do
    end function

    ! In-place NFC on the code points c(1:n); n may change.
    subroutine nfc_cps(c, n)
        integer(int32), allocatable, intent(inout) :: c(:)
        integer, intent(inout) :: n
        integer(int32), allocatable :: d(:), tmp(:)
        integer, allocatable :: cca(:)
        integer :: cnt(0:255)
        integer :: i, j, k, nd, cp, s, t, cc, last, start, sidx, outn, lastcc, comp
        logical :: any_big
        any_big = .false.
        do i = 1, n
            if (c(i) >= 768) then
                any_big = .true.
                exit
            end if
        end do
        if (.not. any_big) return
        allocate(d(max(1, 4 * n + 8)))
        allocate(tmp(size(d)))
        nd = 0
        do i = 1, n
            cp = c(i)
            if (cp >= 44032 .and. cp <= 55203) then          ! Hangul syllable -> jamo
                s = cp - 44032
                nd = nd + 1; d(nd) = 4352 + s / 588
                nd = nd + 1; d(nd) = 4449 + modulo(s, 588) / 28
                t = modulo(s, 28)
                if (t /= 0) then
                    nd = nd + 1; d(nd) = 4519 + t
                end if
            else
                k = 0
                if (cp >= 192) k = find_decomp(cp)
                if (k > 0) then
                    do j = 0, dec_len(k) - 1
                        nd = nd + 1
                        d(nd) = dec_pool(dec_start(k) + j)
                    end do
                else
                    nd = nd + 1
                    d(nd) = cp
                end if
            end if
        end do
        ! canonical ordering: stable sort of each run of non-starters
        allocate(cca(nd))
        do i = 1, nd
            cca(i) = ccc_of(int(d(i)))
        end do
        i = 1
        do while (i <= nd)
            if (cca(i) == 0) then
                i = i + 1
                cycle
            end if
            start = i
            do while (i <= nd)
                if (cca(i) == 0) exit
                i = i + 1
            end do
            if (i - start < 2) cycle
            if (i - start <= 16) then
                do j = start + 1, i - 1
                    cp = d(j)
                    cc = cca(j)
                    k = j - 1
                    do while (k >= start)
                        if (cca(k) <= cc) exit
                        d(k+1) = d(k)
                        cca(k+1) = cca(k)
                        k = k - 1
                    end do
                    d(k+1) = cp
                    cca(k+1) = cc
                end do
            else                      ! counting sort (long runs of marks)
                cnt = 0
                do j = start, i - 1
                    cnt(cca(j)) = cnt(cca(j)) + 1
                end do
                k = start
                do cc = 0, 255
                    t = cnt(cc)
                    cnt(cc) = k
                    k = k + t
                end do
                do j = start, i - 1
                    tmp(cnt(cca(j))) = d(j)
                    cnt(cca(j)) = cnt(cca(j)) + 1
                end do
                d(start:i-1) = tmp(start:i-1)
                do j = start, i - 1
                    cca(j) = ccc_of(int(d(j)))
                end do
            end if
        end do
        ! composition
        outn = 0
        sidx = 0
        lastcc = 0
        do i = 1, nd
            cp = d(i)
            cc = ccc_of(cp)
            if (sidx > 0) then
                last = outn
                if (last == sidx .or. (lastcc /= 0 .and. lastcc < cc)) then
                    comp = compose_pair(int(d(sidx)), cp)
                    if (comp > 0) then
                        d(sidx) = comp
                        cycle
                    end if
                end if
            end if
            outn = outn + 1
            d(outn) = cp
            if (cc == 0) sidx = outn
            lastcc = cc
        end do
        if (outn > size(c)) then
            deallocate(c)
            allocate(c(outn))
        end if
        c(1:outn) = d(1:outn)
        n = outn
    end subroutine

    function nfc_utf8(s) result(r)
        character(*), intent(in) :: s
        character(:), allocatable :: r
        integer(int32), allocatable :: c(:)
        integer :: n
        call utf8_to_cps(s, c, n)
        call nfc_cps(c, n)
        r = cps_to_utf8(c, n)
    end function

    ! ------------------------------------------------------------------
    ! BPE
    ! ------------------------------------------------------------------

    subroutine push_id(ids, n, id)
        integer(int32), allocatable, intent(inout) :: ids(:)
        integer, intent(inout) :: n
        integer(int32), intent(in) :: id
        integer(int32), allocatable :: t(:)
        if (n >= size(ids)) then
            allocate(t(2 * size(ids) + 16))
            t(1:n) = ids(1:n)
            call move_alloc(t, ids)
        end if
        n = n + 1
        ids(n) = id
    end subroutine

    subroutine heap_push(tok, key, l, r)
        type(bpe_tokenizer), intent(inout) :: tok
        integer(int64), intent(in) :: key
        integer(int32), intent(in) :: l, r
        integer :: i, p
        tok%hn = tok%hn + 1
        i = tok%hn
        do while (i > 1)
            p = i / 2
            if (tok%h_key(p) <= key) exit
            tok%h_key(i) = tok%h_key(p)
            tok%h_l(i) = tok%h_l(p)
            tok%h_r(i) = tok%h_r(p)
            i = p
        end do
        tok%h_key(i) = key
        tok%h_l(i) = l
        tok%h_r(i) = r
    end subroutine

    subroutine heap_pop(tok, key, l, r)
        type(bpe_tokenizer), intent(inout) :: tok
        integer(int64), intent(out) :: key
        integer(int32), intent(out) :: l, r
        integer :: i, c, n
        integer(int64) :: k2
        integer(int32) :: l2, r2
        key = tok%h_key(1)
        l = tok%h_l(1)
        r = tok%h_r(1)
        n = tok%hn
        k2 = tok%h_key(n)
        l2 = tok%h_l(n)
        r2 = tok%h_r(n)
        tok%hn = n - 1
        n = n - 1
        if (n == 0) return
        i = 1
        do
            c = 2 * i
            if (c > n) exit
            if (c < n) then
                if (tok%h_key(c+1) < tok%h_key(c)) c = c + 1
            end if
            if (tok%h_key(c) >= k2) exit
            tok%h_key(i) = tok%h_key(c)
            tok%h_l(i) = tok%h_l(c)
            tok%h_r(i) = tok%h_r(c)
            i = c
        end do
        tok%h_key(i) = k2
        tok%h_l(i) = l2
        tok%h_r(i) = r2
    end subroutine

    ! BPE-merge the bytes s and append the resulting ids.
    subroutine bpe_piece(tok, s, ids, nids)
        type(bpe_tokenizer), intent(inout) :: tok
        character(*), intent(in) :: s
        integer(int32), allocatable, intent(inout) :: ids(:)
        integer, intent(inout) :: nids
        integer :: n, i, pos, nx, nn, rank
        integer(int64) :: key
        integer(int32) :: l, r, res
        n = len(s)
        if (n == 0) return
        if (n == 1) then
            call push_id(ids, nids, tok%byte_id(iachar(s(1:1))))
            return
        end if
        if (.not. allocated(tok%w_sym)) then
            allocate(tok%w_sym(0), tok%w_prv(0), tok%w_nxt(0), tok%h_key(0), tok%h_l(0), tok%h_r(0))
        end if
        if (size(tok%w_sym) /= n .or. size(tok%h_key) < 3 * n + 8) then
            if (size(tok%w_sym) < n .or. size(tok%w_sym) > 4 * n + 64) then
                deallocate(tok%w_sym, tok%w_prv, tok%w_nxt)
                allocate(tok%w_sym(n), tok%w_prv(n), tok%w_nxt(n))
            end if
            if (size(tok%h_key) < 3 * n + 8) then
                deallocate(tok%h_key, tok%h_l, tok%h_r)
                allocate(tok%h_key(3 * n + 8), tok%h_l(3 * n + 8), tok%h_r(3 * n + 8))
            end if
        end if
        nn = n
        do i = 1, n
            tok%w_sym(i) = tok%byte_id(iachar(s(i:i)))
            tok%w_prv(i) = i - 1
            tok%w_nxt(i) = i + 1
        end do
        tok%hn = 0
        do i = 1, n - 1
            call pair_find(tok, tok%w_sym(i), tok%w_sym(i+1), rank, res)
            if (rank > 0) call heap_push(tok, int(rank, int64) * 4294967296_int64 + i, tok%w_sym(i), tok%w_sym(i+1))
        end do
        do while (tok%hn > 0)
            call heap_pop(tok, key, l, r)
            pos = int(iand(key, 4294967295_int64))
            if (tok%w_sym(pos) /= l) cycle
            nx = tok%w_nxt(pos)
            if (nx > nn) cycle
            if (tok%w_sym(nx) /= r) cycle
            rank = int(ishft(key, -32))
            tok%w_sym(pos) = tok%mr(rank)
            tok%w_sym(nx) = -1
            tok%w_nxt(pos) = tok%w_nxt(nx)
            if (tok%w_nxt(nx) <= nn) tok%w_prv(tok%w_nxt(nx)) = pos
            if (tok%w_nxt(pos) <= nn) call try_pair(tok, pos, nn)
            if (tok%w_prv(pos) >= 1) call try_pair(tok, tok%w_prv(pos), nn)
        end do
        i = 1
        do while (i <= nn)
            call push_id(ids, nids, tok%w_sym(i))
            i = tok%w_nxt(i)
        end do
    end subroutine

    subroutine try_pair(tok, pos, nn)
        type(bpe_tokenizer), intent(inout) :: tok
        integer, intent(in) :: pos, nn
        integer :: rank, nx
        integer(int32) :: res
        nx = tok%w_nxt(pos)
        if (nx > nn .or. nx < 1) return
        call pair_find(tok, tok%w_sym(pos), tok%w_sym(nx), rank, res)
        if (rank < 0) return
        call heap_push(tok, int(rank, int64) * 4294967296_int64 + pos, tok%w_sym(pos), tok%w_sym(nx))
    end subroutine

    ! Normalize, pre-tokenize and BPE a plain-text segment (no added tokens inside).
    subroutine encode_plain(tok, s, ids, nids)
        type(bpe_tokenizer), intent(inout) :: tok
        character(*), intent(in) :: s
        integer(int32), allocatable, intent(inout) :: ids(:)
        integer, intent(inout) :: nids
        integer(int32), allocatable :: c(:)
        character(:), allocatable :: bytes
        integer :: n, i, e, k, j
        if (len(s) == 0) return
        call utf8_to_cps(s, c, n)
        call nfc_cps(c, n)
        allocate(character(max(4, 4 * n)) :: bytes)
        i = 1
        do while (i <= n)
            e = piece_end(c, n, i)
            k = 0
            do j = i, e - 1
                call put_utf8(bytes, k, int(c(j)))
            end do
            call bpe_piece(tok, bytes(1:k), ids, nids)
            i = e
        end do
    end subroutine

    ! Tokenize UTF-8 text (added tokens such as <|im_start|> are matched literally).
    subroutine encode_text(tok, text, ids)
        type(bpe_tokenizer), intent(inout) :: tok
        character(*), intent(in) :: text
        integer(int32), allocatable, intent(out) :: ids(:)
        integer(int32), allocatable :: buf(:)
        integer :: n, i, seg, a, id, l, nt
        allocate(buf(1024))
        n = 0
        nt = len(text)
        seg = 1
        i = 1
        do while (i <= nt)
            if (tok%first_added(iachar(text(i:i)))) then
                id = -1
                do a = 1, tok%n_added
                    l = token_len(tok, tok%added_id(a))
                    if (l == 0 .or. i + l - 1 > nt) cycle
                    if (text(i:i+l-1) == tok%pool(tok%off(tok%added_id(a))+1:tok%off(tok%added_id(a))+l)) then
                        id = tok%added_id(a)
                        exit
                    end if
                end do
                if (id >= 0) then
                    call encode_plain(tok, text(seg:i-1), buf, n)
                    call push_id(buf, n, int(id, int32))
                    i = i + l
                    seg = i
                    cycle
                end if
            end if
            i = i + 1
        end do
        call encode_plain(tok, text(seg:nt), buf, n)
        allocate(ids(n))
        ids = buf(1:n)
    end subroutine

    ! ------------------------------------------------------------------
    ! detokenization
    ! ------------------------------------------------------------------

    subroutine stream_reset(st, skip_special)
        type(text_stream), intent(out) :: st
        logical, intent(in), optional :: skip_special
        st%npend = 0
        st%skip_special = .true.
        if (present(skip_special)) st%skip_special = skip_special
    end subroutine

    ! Append the text of token id to the stream.  Returns the bytes now
    ! complete in out(1:n); an incomplete UTF-8 tail is held back.
    ! len(out) must be at least 3 * (tok%max_len + 4).
    subroutine stream_feed(tok, st, id, out, n)
        type(bpe_tokenizer), intent(in) :: tok
        type(text_stream), intent(inout) :: st
        integer, intent(in) :: id
        character(*), intent(inout) :: out
        integer, intent(out) :: n
        character(:), allocatable :: w
        integer :: m, i, cp, adv, status
        n = 0
        if (id < 0 .or. id >= tok%n_tokens) return
        if (st%skip_special .and. tok%special(id)) return
        m = token_len(tok, id)
        allocate(character(st%npend + m) :: w)
        if (st%npend > 0) w(1:st%npend) = st%pend(1:st%npend)
        if (m > 0) w(st%npend+1:st%npend+m) = tok%pool(tok%off(id)+1:tok%off(id+1))
        st%npend = 0
        m = len(w)
        i = 1
        do while (i <= m)
            call utf8_step(w, i, m, cp, adv, status)
            if (status == 2) then
                st%pend(1:m-i+1) = w(i:m)
                st%npend = m - i + 1
                return
            end if
            if (n + 4 > len(out)) return
            if (status == 0 .and. adv == 1) then
                n = n + 1
                out(n:n) = w(i:i)
            else
                call put_utf8(out, n, cp)
            end if
            i = i + adv
        end do
    end subroutine

    subroutine stream_flush(st, out, n)
        type(text_stream), intent(inout) :: st
        character(*), intent(inout) :: out
        integer, intent(out) :: n
        n = 0
        if (st%npend > 0) call put_utf8(out, n, 65533)
        st%npend = 0
    end subroutine

    function decode_ids(tok, ids, skip_special) result(text)
        type(bpe_tokenizer), intent(in) :: tok
        integer(int32), intent(in) :: ids(:)
        logical, intent(in), optional :: skip_special
        character(:), allocatable :: text
        type(text_stream) :: st
        character(:), allocatable :: out, buf
        integer :: i, n, k
        integer(int64) :: total
        call stream_reset(st, skip_special)
        total = 16
        do i = 1, size(ids)
            if (ids(i) >= 0 .and. ids(i) < tok%n_tokens) total = total + 3 * token_len(tok, ids(i)) + 8
        end do
        allocate(character(int(total)) :: buf)
        allocate(character(3 * (tok%max_len + 4)) :: out)
        k = 0
        do i = 1, size(ids)
            call stream_feed(tok, st, int(ids(i)), out, n)
            if (n > 0) buf(k+1:k+n) = out(1:n)
            k = k + n
        end do
        call stream_flush(st, out, n)
        if (n > 0) buf(k+1:k+n) = out(1:n)
        k = k + n
        text = buf(1:k)
    end function

    ! ------------------------------------------------------------------
    ! chat template (chat_template.jinja, single user turn)
    ! ------------------------------------------------------------------

    function strip_ws(s) result(r)
        character(*), intent(in) :: s
        character(:), allocatable :: r
        integer :: a, b
        a = 1
        b = len(s)
        do while (a <= b)
            if (index(' '//achar(9)//achar(10)//achar(11)//achar(12)//achar(13), s(a:a)) == 0) exit
            a = a + 1
        end do
        do while (b >= a)
            if (index(' '//achar(9)//achar(10)//achar(11)//achar(12)//achar(13), s(b:b)) == 0) exit
            b = b - 1
        end do
        r = s(a:b)
    end function

    ! Render [system] + user + generation prompt as chat_template.jinja does.
    ! effort: 'xhigh' (the template default), 'medium' or 'low'; it only matters
    ! when thinking is enabled.  thinking=.false. is enable_thinking=false.
    function chat_prompt(user, system, thinking, effort) result(s)
        character(*), intent(in) :: user, system
        logical, intent(in) :: thinking
        character(*), intent(in) :: effort
        character(:), allocatable :: s, instr, sys
        character(1), parameter :: nl = achar(10)
        instr = ''
        if (thinking) then
            if (effort == 'xhigh') then
                instr = 'Reasoning effort is set to xhigh. Please think carefully through the task, validate key '// &
                    'assumptions, consider plausible alternatives, and prioritize correctness, consistency, and '// &
                    'clarity in the final answer.'
            else if (effort == 'low') then
                instr = 'Reasoning effort is set to low. Keep your thinking brief and focused, moving directly to '// &
                    'the conclusion without unnecessary elaboration.'
            end if
        end if
        sys = strip_ws(system)
        s = ''
        if (len(sys) > 0) then
            if (len(instr) > 0) instr = instr//nl//nl
            s = '<|im_start|>system'//nl//instr//sys//'<|im_end|>'//nl
        else if (len(instr) > 0) then
            s = '<|im_start|>system'//nl//instr//'<|im_end|>'//nl
        end if
        s = s//'<|im_start|>user'//nl//strip_ws(user)//'<|im_end|>'//nl//'<|im_start|>assistant'//nl
        if (thinking) then
            s = s//'<think>'//nl
        else
            s = s//'<think>'//nl//nl//'</think>'//nl//nl
        end if
    end function

    ! ------------------------------------------------------------------
    ! JSON string body (without quotes); invalid UTF-8 becomes U+FFFD
    ! ------------------------------------------------------------------

    function json_escape(s) result(r)
        character(*), intent(in) :: s
        character(:), allocatable :: r
        character(:), allocatable :: t, w
        character(16) :: hex
        integer :: i, k, b
        w = sanitize_utf8(s)
        allocate(character(6 * len(w) + 8) :: t)
        k = 0
        do i = 1, len(w)
            b = iachar(w(i:i))
            if (b == 34 .or. b == 92) then
                t(k+1:k+2) = '\'//w(i:i)
                k = k + 2
            else if (b < 32) then
                select case (b)
                case (10)
                    t(k+1:k+2) = '\n'
                    k = k + 2
                case (13)
                    t(k+1:k+2) = '\r'
                    k = k + 2
                case (9)
                    t(k+1:k+2) = '\t'
                    k = k + 2
                case default
                    write(hex, '(z4.4)') b
                    t(k+1:k+6) = '\u'//hex(1:4)
                    k = k + 6
                end select
            else
                k = k + 1
                t(k:k) = w(i:i)
            end if
        end do
        r = t(1:k)
    end function
