    subroutine read_file_bytes(path, text, err)
        character(*), intent(in) :: path
        character(:), allocatable, intent(out) :: text
        character(:), allocatable, intent(out) :: err
        integer :: unit, ios
        integer(int64) :: length
        open(newunit=unit, file=path, access='stream', form='unformatted', status='old', action='read', iostat=ios)
        if (ios /= 0) then
            err = 'cannot open file: '//path
            return
        end if
        inquire(unit=unit, size=length, iostat=ios)
        if (ios /= 0 .or. length < 0 .or. length > 2000000000_int64) then
            err = 'cannot determine file size: '//path
            close(unit)
            return
        end if
        allocate(character(int(length)) :: text, stat=ios)
        if (ios /= 0) then
            err = 'file buffer allocation failed'
            close(unit)
            return
        end if
        if (length > 0) then
            read(unit, pos=1_int64, iostat=ios) text
            if (ios /= 0) err = 'truncated file: '//path
        end if
        close(unit)
    end subroutine

