        integer, intent(inout) :: pos
        do while (pos <= len(buf))
            select case (iachar(buf(pos:pos)))
            case (32, 9, 10, 13)
                pos = pos + 1
            case default
                return
            end select
        end do
    end subroutine

    integer function hex_value(c)
        character, intent(in) :: c
        integer :: v
        v = iachar(c)
        hex_value = -1
        if (v >= 48 .and. v <= 57) hex_value = v - 48
        if (v >= 65 .and. v <= 70) hex_value = v - 55
        if (v >= 97 .and. v <= 102) hex_value = v - 87
    end function

    ! Parse a JSON string at buf(pos:pos)=='"' into raw UTF-8 bytes in out(1:n).
    subroutine json_raw_string(buf, pos, out, n, ok)
        character(*), intent(in) :: buf
        integer, intent(inout) :: pos
        character(*), intent(inout) :: out
        integer, intent(out) :: n
        logical, intent(out) :: ok
        integer :: b, cp, k, h, lo
        ok = .false.
        n = 0
        if (pos > len(buf)) return
        if (buf(pos:pos) /= '"') return
        pos = pos + 1
        do
            if (pos > len(buf)) return
            b = iachar(buf(pos:pos))
            if (b == 34) then
                pos = pos + 1
                ok = .true.
                return
            else if (b == 92) then
                pos = pos + 1
                if (pos > len(buf)) return
                select case (buf(pos:pos))
                case ('"', '\', '/')
                    cp = iachar(buf(pos:pos))
                case ('b')
                    cp = 8
                case ('f')
                    cp = 12
                case ('n')
                    cp = 10
                case ('r')
                    cp = 13
                case ('t')
                    cp = 9
                case ('u')
                    cp = 0
                    if (pos + 4 > len(buf)) return
                    do k = 1, 4
                        h = hex_value(buf(pos+k:pos+k))
                        if (h < 0) return
                        cp = cp * 16 + h
                    end do
                    pos = pos + 4
                    if (cp >= 55296 .and. cp < 56320) then   ! high surrogate: \uXXXX low
                        if (pos + 6 > len(buf)) return
                        if (buf(pos+1:pos+2) /= '\u') return
                        lo = 0
                        do k = 3, 6
                            h = hex_value(buf(pos+k:pos+k))
                            if (h < 0) return
                            lo = lo * 16 + h
                        end do
                        cp = 65536 + (cp - 55296) * 1024 + (lo - 56320)
                        pos = pos + 6
                    end if
                case default
                    return
                end select
                pos = pos + 1
                call put_utf8(out, n, cp)
                if (n > len(out)) return
            else
                n = n + 1
                if (n > len(out)) return
                out(n:n) = buf(pos:pos)
                pos = pos + 1
            end if
        end do
    end subroutine

    ! Parse a vocabulary/merge string: JSON string whose characters are GPT-2
    ! byte symbols; output the bytes they stand for.
    subroutine json_token(tok, buf, pos, out, n, ok)
        type(bpe_tokenizer), intent(in) :: tok
        character(*), intent(in) :: buf
        integer, intent(inout) :: pos
        character(*), intent(inout) :: out
        integer, intent(out) :: n
        logical, intent(out) :: ok
        integer :: b, cp, v
        ok = .false.
        n = 0
        if (pos > len(buf)) return
        if (buf(pos:pos) /= '"') return
        pos = pos + 1
        do
            if (pos > len(buf)) return
            b = iachar(buf(pos:pos))
            if (b == 34) then
                pos = pos + 1
                ok = .true.
                return
            else if (b == 92) then
                pos = pos + 1
                if (pos > len(buf)) return
                select case (buf(pos:pos))
                case ('"', '\', '/')
                    cp = iachar(buf(pos:pos))
                    pos = pos + 1
                case ('u')
                    if (pos + 4 > len(buf)) return
                    cp = 0
                    do v = 1, 4
                        b = hex_value(buf(pos+v:pos+v))
                        if (b < 0) return
                        cp = cp * 16 + b
                    end do
                    pos = pos + 5
                case default
                    return
                end select
            else if (b < 128) then
                cp = b
                pos = pos + 1
            else if (b >= 194 .and. b < 224 .and. pos < len(buf)) then
                cp = (b - 192) * 64 + (iachar(buf(pos+1:pos+1)) - 128)
                pos = pos + 2
            else
                return
            end if
            if (cp < 0 .or. cp > 511) return
            v = tok%u2b(cp)
            if (v < 0) return
            n = n + 1
            if (n > len(out)) return
            out(n:n) = achar(v)
        end do
    end subroutine

    subroutine json_int(buf, pos, value, ok)
        character(*), intent(in) :: buf
        integer, intent(inout) :: pos
        integer, intent(out) :: value
        logical, intent(out) :: ok
        integer :: d
        value = 0
        ok = .false.
        do while (pos <= len(buf))
            d = iachar(buf(pos:pos)) - 48
            if (d < 0 .or. d > 9) exit
            if (value > 200000000) return
            value = value * 10 + d
            ok = .true.
            pos = pos + 1
        end do
    end subroutine

    ! ------------------------------------------------------------------
    ! hash tables
    ! ------------------------------------------------------------------

    integer function str_hash(s, mask)
        character(*), intent(in) :: s
        integer, intent(in) :: mask
        integer(int64) :: h
        integer :: i
        h = 2166136261_int64
        do i = 1, len(s)
            h = ieor(h, int(iachar(s(i:i)), int64))
            h = iand(h * 16777619_int64, 4294967295_int64)
        end do
        h = ieor(h, ishft(h, -15))
        str_hash = int(iand(h, int(mask, int64)))
    end function

    integer function pair_hash(a, b, mask)
        integer(int32), intent(in) :: a, b
        integer, intent(in) :: mask
        integer(int64) :: h
        h = ieor(ishft(int(a, int64) * 73856093_int64, -4), ishft(int(b, int64) * 19349663_int64, -2))
        h = ieor(h, ishft(h, -13))
        pair_hash = int(iand(h, int(mask, int64)))
    end function

    integer function vocab_find(tok, s) result(id)
        type(bpe_tokenizer), intent(in) :: tok
        character(*), intent(in) :: s
        integer :: h, c
        id = -1
        if (len(s) == 0) return
        h = str_hash(s, tok%vmask)
        do
            c = tok%vtab(h)
            if (c == 0) return
            if (token_len(tok, c - 1) == len(s)) then
                if (tok%pool(tok%off(c-1)+1:tok%off(c)) == s) then
                    id = c - 1
                    return
                end if
            end if
            h = iand(h + 1, tok%vmask)
        end do
    end function

    integer function token_len(tok, id)
        type(bpe_tokenizer), intent(in) :: tok
        integer, intent(in) :: id
        token_len = tok%off(id+1) - tok%off(id)
    end function

    function token_text(tok, id) result(s)
        type(bpe_tokenizer), intent(in) :: tok
        integer, intent(in) :: id
        character(:), allocatable :: s
        if (id < 0 .or. id >= tok%n_tokens) then
            s = ''
        else
            s = tok%pool(tok%off(id)+1:tok%off(id+1))
        end if
    end function

    logical function is_stop_token(tok, id)
        type(bpe_tokenizer), intent(in) :: tok
        integer, intent(in) :: id
        is_stop_token = .false.
        if (allocated(tok%eos)) is_stop_token = any(tok%eos == id)
    end function

    subroutine pair_find(tok, a, b, rank, res)
        type(bpe_tokenizer), intent(in) :: tok
        integer(int32), intent(in) :: a, b
        integer, intent(out) :: rank
        integer(int32), intent(out) :: res
        integer :: h, m
        rank = -1
        res = -1
        h = pair_hash(a, b, tok%mmask)
        do
            m = tok%mtab(h)
            if (m == 0) return
            if (tok%ma(m) == a .and. tok%mb(m) == b) then
                rank = m
                res = tok%mr(m)
                return
            end if
            h = iand(h + 1, tok%mmask)
        end do
    end subroutine

    ! ------------------------------------------------------------------
    ! loading
    ! ------------------------------------------------------------------

    subroutine init_byte_map(tok)
        type(bpe_tokenizer), intent(inout) :: tok
        integer :: b, n
        logical :: direct
        tok%u2b = -1
        n = 0
        do b = 0, 255
            direct = (b >= 33 .and. b <= 126) .or. (b >= 161 .and. b <= 172) .or. (b >= 174)
            if (direct) then
                tok%b2u(b) = b
            else
                tok%b2u(b) = 256 + n
                n = n + 1
            end if
            tok%u2b(tok%b2u(b)) = b
        end do
    end subroutine

    subroutine load_tokenizer(directory, tok, err)
        character(*), intent(in) :: directory
        type(bpe_tokenizer), intent(inout) :: tok
        character(:), allocatable, intent(out) :: err
        character(:), allocatable :: buf, tmp, gen
        character(:), allocatable :: ferr
        character(len=max_piece_bytes) :: ta, tb, tc
        integer, allocatable :: eid(:), estart(:), elen(:)
        integer, allocatable :: aid(:), alen(:), astart(:), alen_tmp(:)
        logical, allocatable :: aspec(:)
        character(:), allocatable :: apool
        integer :: pos, p0, n, na, nb, ne, ecap, tpn, i, j, id, maxid, vsize, a_id, b_id, r_id, h, nm
        integer :: tcap, acap, apn
        integer(int32) :: res
        integer :: rank
        logical :: ok
        character(:), allocatable :: keybuf
        integer :: kn, ival

        call init_byte_map(tok)
        call read_file_bytes(directory//'/tokenizer.json', buf, ferr)
        if (allocated(ferr)) then
            err = ferr
            return
        end if

        ! ---- added tokens
        allocate(character(max_piece_bytes) :: keybuf)
        acap = 64
        allocate(aid(acap), alen(acap), astart(acap), aspec(acap))
        allocate(character(8192) :: apool)
        na = 0
        apn = 0
        p0 = index(buf, '"added_tokens"')
        if (p0 > 0) then
            pos = p0 + 14
            call skip_ws(buf, pos)
            if (buf(pos:pos) /= ':') then
                err = 'tokenizer.json: malformed added_tokens'
                return
            end if
            pos = pos + 1
            call skip_ws(buf, pos)
            if (buf(pos:pos) /= '[') then
                err = 'tokenizer.json: added_tokens is not an array'
                return
            end if
            pos = pos + 1
            do
                call skip_ws(buf, pos)
                if (pos > len(buf)) then
                    err = 'tokenizer.json: truncated added_tokens'
                    return
                end if
                if (buf(pos:pos) == ']') exit
                if (buf(pos:pos) == ',') then
                    pos = pos + 1
                    cycle
                end if
                if (buf(pos:pos) /= '{') then
                    err = 'tokenizer.json: malformed added token'
                    return
                end if
                pos = pos + 1
                na = na + 1
                if (na > acap) then
                    call grow_added(aid, alen, astart, aspec, acap)
                end if
                aid(na) = -1
                alen(na) = 0
                astart(na) = apn
                aspec(na) = .false.
                do
                    call skip_ws(buf, pos)
                    if (pos > len(buf)) then
                        err = 'tokenizer.json: truncated added token'
                        return
                    end if
                    if (buf(pos:pos) == '}') then
                        pos = pos + 1
                        exit
                    end if
                    if (buf(pos:pos) == ',') then
                        pos = pos + 1
                        cycle
                    end if
                    call json_raw_string(buf, pos, keybuf, kn, ok)
                    if (.not. ok) then
                        err = 'tokenizer.json: bad added token key'
                        return
                    end if
                    call skip_ws(buf, pos)
                    pos = pos + 1   ! ':'
                    call skip_ws(buf, pos)
                    if (buf(pos:pos) == '"') then
                        if (keybuf(1:kn) == 'content') then
                            do while (apn + max_piece_bytes > len(apool))
                                call grow_chars(apool)
                            end do
                            call json_raw_string(buf, pos, apool(apn+1:), n, ok)
                            if (.not. ok) then
                                err = 'tokenizer.json: bad added token content'
                                return
                            end if
                            alen(na) = n
                            apn = apn + n
                        else
                            call json_raw_string(buf, pos, ta, n, ok)
                        end if
                    else if (buf(pos:pos) >= '0' .and. buf(pos:pos) <= '9') then
                        call json_int(buf, pos, ival, ok)
                        if (keybuf(1:kn) == 'id') aid(na) = ival
                    else if (buf(pos:pos) == 't') then
                        if (keybuf(1:kn) == 'special') aspec(na) = .true.
                        pos = pos + 4
                    else if (buf(pos:pos) == 'f') then
                        pos = pos + 5
                    else if (buf(pos:pos) == 'n') then
                        pos = pos + 4
                    else
                        err = 'tokenizer.json: unexpected added token value'
                        return
                    end if
                end do
            end do
        end if

        ! ---- vocabulary (phase A: collect entries in file order)
        p0 = index(buf, '"vocab"')
        if (p0 == 0) then
            err = 'tokenizer.json: no vocab'
            return
        end if
        pos = p0 + 7
        call skip_ws(buf, pos)
        pos = pos + 1   ! ':'
        call skip_ws(buf, pos)
        if (buf(pos:pos) /= '{') then
            err = 'tokenizer.json: vocab is not an object'
            return
        end if
        pos = pos + 1
        ecap = 262144
        allocate(eid(ecap), estart(ecap), elen(ecap))
        allocate(character(4194304) :: tmp)
        ne = 0
        tpn = 0
        maxid = -1
        do
            call skip_ws(buf, pos)
            if (pos > len(buf)) then
                err = 'tokenizer.json: truncated vocab'
                return
            end if
            if (buf(pos:pos) == '}') then
                pos = pos + 1
                exit
            end if
            if (buf(pos:pos) == ',') then
                pos = pos + 1
                cycle
            end if
            call json_token(tok, buf, pos, ta, n, ok)
            if (.not. ok) then
                err = 'tokenizer.json: bad vocab key (not a byte-level symbol string)'
                return
            end if
            call skip_ws(buf, pos)
            if (buf(pos:pos) /= ':') then
                err = 'tokenizer.json: expected ":" in vocab'
                return
            end if
            pos = pos + 1
            call skip_ws(buf, pos)
            call json_int(buf, pos, id, ok)
            if (.not. ok) then
                err = 'tokenizer.json: bad vocab id'
                return
            end if
            ne = ne + 1
            if (ne > ecap) call grow_int3(eid, estart, elen, ecap)
            if (tpn + n > len(tmp)) call grow_chars(tmp)
            tmp(tpn+1:tpn+n) = ta(1:n)
            eid(ne) = id
            estart(ne) = tpn
            elen(ne) = n
            tpn = tpn + n
            maxid = max(maxid, id)
        end do
        do i = 1, na
            maxid = max(maxid, aid(i))
        end do
        if (maxid < 0 .or. maxid >= 1048575) then
            err = 'tokenizer.json: token ids must be in 0..2^20-2'
            return
        end if
        tok%n_tokens = maxid + 1

        ! final layout by id
        allocate(tok%off(0:tok%n_tokens), tok%special(0:tok%n_tokens-1))
        allocate(alen_tmp(0:tok%n_tokens-1))
        alen_tmp = 0
        tok%special = .false.
        do i = 1, ne
            alen_tmp(eid(i)) = elen(i)
        end do
        do i = 1, na
            if (aid(i) < 0) then
                err = 'tokenizer.json: added token without id'
                return
            end if
            alen_tmp(aid(i)) = alen(i)
            tok%special(aid(i)) = aspec(i)
        end do
        tok%off(0) = 0
        do i = 0, tok%n_tokens - 1
            tok%off(i+1) = tok%off(i) + alen_tmp(i)
            tok%max_len = max(tok%max_len, alen_tmp(i))
        end do
        deallocate(alen_tmp)
        allocate(character(max(1, tok%off(tok%n_tokens))) :: tok%pool)
        do i = 1, ne
            id = eid(i)
            if (elen(i) > 0) tok%pool(tok%off(id)+1:tok%off(id)+elen(i)) = tmp(estart(i)+1:estart(i)+elen(i))
        end do
        deallocate(tmp)
        do i = 1, na
            id = aid(i)
            if (alen(i) > 0) tok%pool(tok%off(id)+1:tok%off(id)+alen(i)) = apool(astart(i)+1:astart(i)+alen(i))
        end do

        ! vocabulary hash (regular vocabulary only, never the added tokens)
        vsize = 1048576
        tok%vmask = vsize - 1
        allocate(tok%vtab(0:tok%vmask))
        tok%vtab = 0
        do i = 1, ne
            id = eid(i)
            h = str_hash(tok%pool(tok%off(id)+1:tok%off(id+1)), tok%vmask)
            do while (tok%vtab(h) /= 0)
                h = iand(h + 1, tok%vmask)
            end do
            tok%vtab(h) = id + 1
        end do
        do b_id = 0, 255
            ta(1:1) = achar(b_id)
            id = vocab_find(tok, ta(1:1))
            if (id < 0) then
                err = 'tokenizer.json: vocabulary lacks a single-byte token'
                return
            end if
            tok%byte_id(b_id) = id
        end do

        ! ---- merges
        p0 = index(buf, '"merges"')
        if (p0 == 0) then
            err = 'tokenizer.json: no merges'
            return
        end if
        pos = p0 + 8
        call skip_ws(buf, pos)
        pos = pos + 1
        call skip_ws(buf, pos)
        if (buf(pos:pos) /= '[') then
            err = 'tokenizer.json: merges is not an array'
            return
        end if
        pos = pos + 1
        tcap = 262144
        allocate(tok%ma(tcap), tok%mb(tcap), tok%mr(tcap))
        allocate(tok%mtab(0:vsize-1))
        tok%mmask = vsize - 1
        tok%mtab = 0
        nm = 0
        do
            call skip_ws(buf, pos)
            if (pos > len(buf)) then
                err = 'tokenizer.json: truncated merges'
                return
            end if
            if (buf(pos:pos) == ']') exit
            if (buf(pos:pos) == ',') then
                pos = pos + 1
                cycle
            end if
            if (buf(pos:pos) == '[') then
                pos = pos + 1
                call skip_ws(buf, pos)
                call json_token(tok, buf, pos, ta, n, ok)
                if (.not. ok) then
                    err = 'tokenizer.json: bad merge'
                    return
                end if
                call skip_ws(buf, pos)
                pos = pos + 1
                call skip_ws(buf, pos)
                call json_token(tok, buf, pos, tb, nb, ok)
                if (.not. ok) then
                    err = 'tokenizer.json: bad merge'
                    return
                end if
                call skip_ws(buf, pos)
                pos = pos + 1   ! ']'
            else if (buf(pos:pos) == '"') then
                call json_token_pair(tok, buf, pos, ta, n, tb, nb, ok)
                if (.not. ok) then
                    err = 'tokenizer.json: bad merge string'
                    return
                end if
            else
                err = 'tokenizer.json: unexpected merge entry'
                return
            end if
            a_id = vocab_find(tok, ta(1:n))
            b_id = vocab_find(tok, tb(1:nb))
            if (n + nb > max_piece_bytes) cycle
            tc(1:n) = ta(1:n)
            tc(n+1:n+nb) = tb(1:nb)
            r_id = vocab_find(tok, tc(1:n+nb))
            if (a_id < 0 .or. b_id < 0 .or. r_id < 0) cycle
            call pair_find(tok, int(a_id, int32), int(b_id, int32), rank, res)
            if (rank > 0) cycle
            nm = nm + 1
            if (nm > tcap) call grow_int3_32(tok%ma, tok%mb, tok%mr, tcap)
            tok%ma(nm) = a_id
            tok%mb(nm) = b_id
            tok%mr(nm) = r_id
            h = pair_hash(int(a_id, int32), int(b_id, int32), tok%mmask)
            do while (tok%mtab(h) /= 0)
                h = iand(h + 1, tok%mmask)
            end do
            tok%mtab(h) = nm
        end do
        tok%n_merges = nm
        deallocate(buf)

        ! ---- added tokens: sort longest first, remember first bytes
        tok%n_added = na
        allocate(tok%added_id(na))
        do i = 1, na
            tok%added_id(i) = aid(i)
        end do
        do i = 2, na
            id = tok%added_id(i)
            j = i - 1
            do while (j >= 1)
                if (token_len(tok, tok%added_id(j)) >= token_len(tok, id)) exit
                tok%added_id(j+1) = tok%added_id(j)
                j = j - 1
            end do
            tok%added_id(j+1) = id
        end do
        do i = 1, na
            id = tok%added_id(i)
            if (token_len(tok, id) > 0) then
                tok%first_added(iachar(tok%pool(tok%off(id)+1:tok%off(id)+1))) = .true.
            end if
            select case (token_text(tok, id))
            case ('<|im_start|>')
                tok%im_start = id
            case ('<|im_end|>')
                tok%im_end = id
            case ('<|endoftext|>')
                tok%endoftext = id
            end select
        end do

        ! ---- stop ids from generation_config.json (fallback: im_end, endoftext)
        call read_file_bytes(directory//'/generation_config.json', gen, ferr)
        allocate(tok%eos(0))
        if (.not. allocated(ferr)) call parse_eos(gen, tok)
        if (size(tok%eos) == 0) then
            deallocate(tok%eos)
            allocate(tok%eos(2))
            tok%eos = [tok%im_end, tok%endoftext]
        end if
    end subroutine

    subroutine parse_eos(gen, tok)
        character(*), intent(in) :: gen
        type(bpe_tokenizer), intent(inout) :: tok
        integer :: p, v, cnt
        integer(int32) :: tmp(16)
        logical :: ok, arr
        p = index(gen, '"eos_token_id"')
        if (p == 0) return
        p = p + 14
        call skip_ws(gen, p)
        p = p + 1
        call skip_ws(gen, p)
        arr = .false.
        if (p <= len(gen)) then
            if (gen(p:p) == '[') then
                arr = .true.
                p = p + 1
            end if
        end if
        cnt = 0
        do
            call skip_ws(gen, p)
            if (p > len(gen)) exit
            if (gen(p:p) == ',') then
                p = p + 1
                cycle
            end if
            call json_int(gen, p, v, ok)
            if (.not. ok) exit
            if (cnt < 16) then
                cnt = cnt + 1
                tmp(cnt) = v
            end if
            if (.not. arr) exit
        end do
        deallocate(tok%eos)
        allocate(tok%eos(cnt))
        tok%eos = tmp(1:cnt)
    end subroutine

    ! "a b" merge strings (older tokenizer.json files)
    subroutine json_token_pair(tok, buf, pos, ta, na, tb, nb, ok)
        type(bpe_tokenizer), intent(in) :: tok
        character(*), intent(in) :: buf
        integer, intent(inout) :: pos
        character(*), intent(inout) :: ta, tb
        integer, intent(out) :: na, nb
        logical, intent(out) :: ok
        integer :: p, q
        ok = .false.
        na = 0
        nb = 0
        q = pos + 1
        p = q
        do while (p <= len(buf))
            if (buf(p:p) == ' ' .or. buf(p:p) == '"') exit
            p = p + 1
        end do
        if (p > len(buf)) return
        if (buf(p:p) /= ' ') return
        ! reuse json_token on a temporary quoted copy of each half
        block
            character(:), allocatable :: s
            integer :: pp
            s = '"'//buf(q:p-1)//'"'
            pp = 1
            call json_token(tok, s, pp, ta, na, ok)
            if (.not. ok) return
            q = p + 1
            p = q
            do while (p <= len(buf))
                if (buf(p:p) == '"') exit
                p = p + 1
            end do
            if (p > len(buf)) then
                ok = .false.
                return
            end if
            s = '"'//buf(q:p-1)//'"'
            pp = 1
            call json_token(tok, s, pp, tb, nb, ok)
            pos = p + 1
        end block
    end subroutine

