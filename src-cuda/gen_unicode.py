# Generates unicode_tables.h: code point ranges of the Unicode general categories
# L* (letters) and N* (numbers), used by the tokenizer's pre-tokenizer regex
# (\p{L} and \p{N}). Run: python3 gen_unicode.py > unicode_tables.h
import sys
import unicodedata


def ranges(prefix):
    out, start = [], None
    for cp in range(0x110000 + 1):
        inside = cp < 0x110000 and unicodedata.category(chr(cp)).startswith(prefix)
        if inside and start is None:
            start = cp
        elif not inside and start is not None:
            out.append((start, cp - 1))
            start = None
    return out


def emit(name, rs):
    print(f"static const uint32_t {name}[][2] = {{")
    for i in range(0, len(rs), 6):
        print("    " + " ".join(f"{{0x{a:X}, 0x{b:X}}}," for a, b in rs[i:i + 6]))
    print("};")


print(f"// Generated by gen_unicode.py from Python {sys.version.split()[0]} unicodedata "
      f"(Unicode {unicodedata.unidata_version}). Do not edit.")
print("#pragma once\n#include <stdint.h>")
emit("UNI_LETTER", ranges("L"))
emit("UNI_NUMBER", ranges("N"))
